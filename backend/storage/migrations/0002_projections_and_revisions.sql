CREATE FUNCTION track_paper_raw_version() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    record JSONB := to_jsonb(NEW);
BEGIN
    INSERT INTO paper_raw_versions(namespace,user_id,kind,record_id,revision)
    VALUES(NEW.namespace,NEW.user_id,TG_ARGV[0],record->>TG_ARGV[1],1)
    ON CONFLICT(namespace,user_id,kind,record_id) DO UPDATE
        SET revision=paper_raw_versions.revision+1;
    RETURN NEW;
END;
$$;
