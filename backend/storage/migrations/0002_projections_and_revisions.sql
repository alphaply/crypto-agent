-- Source revisions serialize against publication checks and catch late identity
-- commits, updates and deletes. They are scoped to each reader's original input.
CREATE TABLE execution_source_revisions (
    account_scope TEXT NOT NULL,
    symbol TEXT NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0,
    storage_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    PRIMARY KEY (account_scope, symbol)
);
CREATE TABLE plan_source_revisions (
    symbol TEXT PRIMARY KEY,
    revision BIGINT NOT NULL DEFAULT 0,
    storage_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE
);
CREATE TABLE paper_source_revisions (
    namespace TEXT NOT NULL,
    user_id TEXT NOT NULL,
    revision BIGINT NOT NULL DEFAULT 0,
    storage_id BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    PRIMARY KEY (namespace, user_id)
);
ALTER TABLE execution_plan_index_runs ADD COLUMN source_revision BIGINT NOT NULL DEFAULT -1;

-- Raw JSON remains authoritative TEXT. Invalid legacy payloads do not become
-- valid facts merely because a projection or source witness is maintained.
CREATE FUNCTION storage_json(value TEXT) RETURNS JSONB
LANGUAGE plpgsql IMMUTABLE STRICT AS $$
BEGIN
    RETURN value::jsonb;
EXCEPTION WHEN invalid_text_representation OR numeric_value_out_of_range THEN
    RETURN NULL;
END;
$$;

CREATE FUNCTION project_protection_activity() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    parsed JSONB;
    projected_state TEXT := 'UNKNOWN';
    projected_updated DOUBLE PRECISION;
    payload_size BIGINT;
    capacity_enabled BOOLEAN := COALESCE(NULLIF(current_setting('crypto.capacity_enabled', true), '')::boolean, true);
    maximum BIGINT := COALESCE(NULLIF(current_setting('crypto.max_record_bytes', true), '')::bigint, 4194304);
BEGIN
    IF TG_OP = 'DELETE' THEN
        DELETE FROM protection_plan_activity WHERE plan_rowid = OLD.storage_id;
        RETURN OLD;
    END IF;
    payload_size := octet_length(convert_to(NEW.payload, 'UTF8'));
    IF NOT capacity_enabled OR payload_size <= maximum THEN
        parsed := storage_json(NEW.payload);
        IF jsonb_typeof(parsed) = 'object' THEN
            projected_state := COALESCE(parsed->>'state', 'UNKNOWN');
            IF jsonb_typeof(parsed->'updated_at') = 'number' THEN
                BEGIN
                    projected_updated := (parsed->>'updated_at')::double precision;
                EXCEPTION WHEN numeric_value_out_of_range THEN
                    projected_updated := NULL;
                END;
            END IF;
        END IF;
    END IF;
    INSERT INTO protection_plan_activity(plan_rowid, config_id, state, updated_at, payload_bytes)
    VALUES(NEW.storage_id, NEW.config_id, projected_state, projected_updated, payload_size)
    ON CONFLICT(plan_rowid) DO UPDATE SET config_id=EXCLUDED.config_id,
        state=EXCLUDED.state, updated_at=EXCLUDED.updated_at, payload_bytes=EXCLUDED.payload_bytes;
    RETURN NEW;
END;
$$;
CREATE TRIGGER protection_activity_write AFTER INSERT OR UPDATE OR DELETE
    ON real_protection_plans FOR EACH ROW EXECUTE FUNCTION project_protection_activity();

