CREATE FUNCTION track_execution_source_revision() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    prior JSONB;
    following JSONB;
    scope RECORD;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        prior := CASE WHEN TG_TABLE_NAME = 'real_protection_events'
            THEN storage_json(OLD.payload) ELSE to_jsonb(OLD) END;
    END IF;
    IF TG_OP <> 'DELETE' THEN
        following := CASE WHEN TG_TABLE_NAME = 'real_protection_events'
            THEN storage_json(NEW.payload) ELSE to_jsonb(NEW) END;
    END IF;
    FOR scope IN
        SELECT DISTINCT value->>'account_scope' AS account_scope, value->>'symbol' AS symbol
        FROM (VALUES(prior),(following)) AS sources(value)
        WHERE value->>'account_scope' IS NOT NULL AND value->>'symbol' IS NOT NULL
        ORDER BY account_scope,symbol
    LOOP
        INSERT INTO execution_source_revisions(account_scope,symbol,revision)
        VALUES(scope.account_scope,scope.symbol,1)
        ON CONFLICT(account_scope,symbol) DO UPDATE
            SET revision=execution_source_revisions.revision+1;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE TRIGGER execution_fills_revision AFTER INSERT OR UPDATE OR DELETE ON execution_fills
    FOR EACH ROW EXECUTE FUNCTION track_execution_source_revision();
CREATE TRIGGER execution_links_revision AFTER INSERT OR UPDATE OR DELETE ON execution_order_links
    FOR EACH ROW EXECUTE FUNCTION track_execution_source_revision();
CREATE TRIGGER execution_protection_revision AFTER INSERT OR UPDATE OR DELETE ON real_protection_events
    FOR EACH ROW EXECUTE FUNCTION track_execution_source_revision();

CREATE FUNCTION track_plan_source_revision() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    old_symbol TEXT;
    new_symbol TEXT;
    affected TEXT;
BEGIN
    IF TG_OP <> 'INSERT' THEN old_symbol := OLD.symbol; END IF;
    IF TG_OP <> 'DELETE' THEN new_symbol := NEW.symbol; END IF;
    FOR affected IN
        SELECT DISTINCT symbol FROM (VALUES(old_symbol),(new_symbol)) AS sources(symbol)
        WHERE symbol IS NOT NULL ORDER BY symbol
    LOOP
        INSERT INTO plan_source_revisions(symbol,revision) VALUES(affected,1)
        ON CONFLICT(symbol) DO UPDATE SET revision=plan_source_revisions.revision+1;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE TRIGGER plan_orders_revision AFTER INSERT OR UPDATE OR DELETE ON orders
    FOR EACH ROW EXECUTE FUNCTION track_plan_source_revision();
CREATE TRIGGER plan_events_revision AFTER INSERT OR UPDATE OR DELETE ON real_protection_events
    FOR EACH ROW EXECUTE FUNCTION track_plan_source_revision();
CREATE TRIGGER plan_plans_revision AFTER INSERT OR UPDATE OR DELETE ON real_protection_plans
    FOR EACH ROW EXECUTE FUNCTION track_plan_source_revision();

CREATE FUNCTION track_paper_source_revision() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    prior JSONB;
    following JSONB;
    scope RECORD;
BEGIN
    IF TG_OP <> 'INSERT' THEN prior := to_jsonb(OLD); END IF;
    IF TG_OP <> 'DELETE' THEN following := to_jsonb(NEW); END IF;
    FOR scope IN
        SELECT DISTINCT value->>'namespace' AS namespace, value->>'user_id' AS user_id
        FROM (VALUES(prior),(following)) AS sources(value)
        WHERE value IS NOT NULL ORDER BY namespace,user_id
    LOOP
        INSERT INTO paper_source_revisions(namespace,user_id,revision)
        VALUES(scope.namespace,scope.user_id,1)
        ON CONFLICT(namespace,user_id) DO UPDATE SET revision=paper_source_revisions.revision+1;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE TRIGGER paper_operations_revision AFTER INSERT OR UPDATE OR DELETE ON paper_operations
    FOR EACH ROW EXECUTE FUNCTION track_paper_source_revision();
